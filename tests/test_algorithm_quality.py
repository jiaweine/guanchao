def _auc(rows):
    positives = [score for label, score in rows if label == 1]
    negatives = [score for label, score in rows if label == 0]
    wins = sum(1.0 if p > n else 0.5 if p == n else 0.0 for p in positives for n in negatives)
    return wins / (len(positives) * len(negatives))


def test_curated_weibo_holdout_keeps_ranking_and_default_threshold_quality_high():
    detector = MarketingDetector()
    rows = []
    for label, handle, bio, posts in CASES:
        account = AccountSnapshot.from_dict({
            "platform": "weibo",
            "handle": handle,
            "bio": bio,
            "posts": [{"id": f"{handle}-{i}", "text": text} for i, text in enumerate(posts)],
        })
        rows.append((label, detector.analyze(account).marketing_likelihood))
    accuracy = sum((score >= detector.calibration.decision_threshold) == bool(label) for label, score in rows) / len(rows)
    assert _auc(rows) >= 0.98
    assert accuracy >= 0.95
